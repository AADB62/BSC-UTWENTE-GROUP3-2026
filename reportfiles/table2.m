% table_timecourse.m  -  LaTeX table of the response to a single dose (reads results.mat)
clear; clc;
root = fileparts(fileparts(mfilename('fullpath')));
load(fullfile(root,'results.mat'));              % res, fList, DList
fShow = [1 0.5 0.2 0.1 0.05 0.02 0.01];
dShow = [100 250];

outDir = fullfile(root,'tables');
if ~exist(outDir,'dir'), mkdir(outDir); end
fid = fopen(fullfile(outDir,'tab_timecourse.tex'),'w');
w = @(s) fprintf(fid,'%s\n',s);
w('% generated by table_timecourse.m - do not edit by hand');
w('\begin{table}[ht]');
w('\centering');
w('\small');
w(['\caption{Metrics of the response of extracellular dopamine to a single dose over the $24$ h window. ' ...
   'Peak: maximum of $\delta eda$ (Eq.~\eqref{eq:dev}); relative rise: peak divided by the equilibrium $eda$ of the same $f$; ' ...
   '$t_{peak}$: time of the peak; AUC: area under $\delta eda$; $t_{1/2}$: time during which $\delta eda$ stays above half of its peak; ' ...
   '$t_{>\theta}$: time during which $eda$ stays above the reference level $\theta$ of Eq.~\eqref{eq:theta} ' ...
   '(not defined, ``--'''', when the equilibrium itself is above $\theta$).}']);
w('\label{tab:sim:timecourse}');
w('\begin{tabular}{@{}crrrrrr@{}}');
w('\toprule');
w('$f$ & Peak [nM] & Rel.\ rise [\%] & $t_{peak}$ [h] & AUC [nM\,h] & $t_{1/2}$ [h] & $t_{>\theta}$ [h] \\');
for D = dShow
    i = find(DList == D, 1);
    w('\midrule');
    w(sprintf('\\multicolumn{7}{l}{$D=%d$ mg} \\\\', D));
    for f = fShow
        j = find(abs(fList-f) < 1e-9);
        m = res(i,j).m;
        if m.baseline_above, ta = '--'; else, ta = sprintf('%.1f', m.t_above); end
        w(sprintf('%g & %.2f & %.0f & %.2f & %.1f & %.2f & %s \\\\', f, m.peak*1e3, ...
                  100*m.rel_rise, m.t_peak, m.auc*1e3, m.t_half, ta));
    end
end
w('\bottomrule');
w('\end{tabular}');
w('\end{table}');
fclose(fid);
fprintf('LaTeX table written to %s\n', fullfile(outDir,'tab_timecourse.tex'));