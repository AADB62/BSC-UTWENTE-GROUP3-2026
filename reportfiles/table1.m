% baseline_check.m  -  baseline (D = 0), autoreceptor counterfactual and LaTeX table
clear; clc;
root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'parameters'), fullfile(root,'model'), fullfile(root,'analysis'));
load(fullfile(root,'results.mat'));              % res, fList
p     = params();
fShow = [1 0.5 0.2 0.1 0.05 0.02 0.01];
nF    = numel(fShow);
e1    = res(1,1).xe(9);                          % healthy eda_eq (uM); res(1,:) is D = 0
opts  = optimoptions('fsolve','Display','off','FunctionTolerance',1e-12, ...
        'StepTolerance',1e-14,'TypicalX',[2.6;79;0.002]);

T   = zeros(nF,8);   % f, cda, vda, eda[nM], change%, g, eda(g=1)[nM], change%
VTH = zeros(nF,1);
for k = 1:nF
    f  = fShow(k);
    j  = find(abs(fList-f) < 1e-9);
    xe = res(1,j).xe;                            % saved equilibrium
    fd = dopamine_fluxes(0, xe(9), xe(4), xe(5), f, p);
    z  = fsolve(@(y) dablock(y,f,p,1), [2.65;79;0.002], opts);   % autoreceptor off (g = 1)
    if k == 1, e1n = z(3); end
    VTH(k) = fd.VTH;
    T(k,:) = [f, xe(4), xe(5), xe(9)*1e3, 100*(xe(9)/e1-1), ...
              g_auto(xe(9),p.eds), z(3)*1e3, 100*(z(3)/e1n-1)];
end

% ---- console ----
fprintf('%5s %7s %7s %9s %8s %7s %8s | %11s %8s\n', ...
        'f','cda','vda','eda[nM]','change%','g','VTH','eda g=1[nM]','change%');
for k = 1:nF
    fprintf('%5.2f %7.3f %7.2f %9.4f %+8.1f %7.3f %8.1f | %11.4f %+8.1f\n', ...
            T(k,1:5), T(k,6), VTH(k), T(k,7:8));
end

% ---- LaTeX table ----
outDir = fullfile(root,'tables');
if ~exist(outDir,'dir'), mkdir(outDir); end
fid = fopen(fullfile(outDir,'tab_baseline.tex'),'w');
w = @(s) fprintf(fid,'%s\n',s);
w('% generated by baseline_check.m - do not edit by hand');
w('\begin{table}[ht]');
w('\centering');
w('\small');
w(['\caption{Equilibrium of the dopamine block for $D=0$ and each fraction of surviving terminals $f$. ' ...
   '$\overline{eda}$ is the extracellular dopamine, $\Delta$ its change relative to $f=1$, and $g$ the ' ...
   'autoreceptor factor of Eq.~\eqref{eq:impl:g} evaluated at equilibrium. The last two columns give the ' ...
   'extracellular dopamine obtained when the autoreceptor feedback is removed ($g=1$ in the equilibrium ' ...
   'equations), which isolates the contribution of the autoreceptor to the compensation. ' ...
   'Values of cda and vda in $\mu$M, and of $eda$ in nM.}']);
w('\label{tab:sim:baseline}');
w('\begin{tabular}{@{}crrrrrrr@{}}');
w('\toprule');
w(' & & & \multicolumn{3}{c}{with autoreceptor} & \multicolumn{2}{c}{$g=1$} \\');
w('\cmidrule(lr){4-6}\cmidrule(l){7-8}');
w('$f$ & $\overline{cda}$ & $\overline{vda}$ & $\overline{eda}$ & $\Delta$ [\%] & $g$ & $\overline{eda}$ & $\Delta$ [\%] \\');
w('\midrule');
for k = 1:nF
    w(sprintf('%g & %.3f & %.2f & %.3f & %s & %.2f & %.3f & %s \\\\', ...
        T(k,1), T(k,2), T(k,3), T(k,4), fmtD(T(k,5)), T(k,6), T(k,7), fmtD(T(k,8))));
end
w('\bottomrule');
w('\end{tabular}');
w('\end{table}');
fclose(fid);
fprintf('\nLaTeX table written to %s\n', fullfile(outDir,'tab_baseline.tex'));

function s = fmtD(x)
% percentage change as a LaTeX string; exact zero is printed without sign
    if abs(x) < 0.05, s = '0'; else, s = sprintf('$%.1f$', x); end
end

function r = dablock(y, f, p, gfix)
% Dopamine block (cda, vda, eda) at equilibrium; body and 5-HT states are zero; g fixed to gfix
    cda = y(1);  vda = y(2);  eda = y(3);
    num  = p.VmTH*p.tyr*p.bh4;
    den  = p.tyr*p.bh4 + p.Ktyr*p.bh4 + p.Ktyr*p.Kbh4*(1 + cda/p.Kicda);
    VTH  = 0.56/(1 + p.tyr/p.Kityr)*gfix*num/den;
    VMAT = mm(p.VmM, p.KM, cda) - p.kout*vda;
    VDAT = mm(p.VmD, p.KD, eda);
    r = [ VTH - VMAT + VDAT - p.kMAO*cda;
          VMAT - p.fire*vda;
          p.fire*vda - VDAT - mm(p.VmC, p.KC, eda) - (p.k0/f)*eda ];
end