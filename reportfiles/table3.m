% table_doseresponse.m  -  LaTeX table of the dose-response (reads results.mat)
clear; clc;
root = fileparts(fileparts(mfilename('fullpath')));
load(fullfile(root,'results.mat'));              % res, fList, DList
fShow = [1 0.2 0.05 0.01];
dShow = [10 100 250 400 1800];

outDir = fullfile(root,'tables');
if ~exist(outDir,'dir'), mkdir(outDir); end
fid = fopen(fullfile(outDir,'tab_doseresponse.tex'),'w');
w = @(s) fprintf(fid,'%s\n',s);
w('% generated by table_doseresponse.m - do not edit by hand');
w('\begin{table}[ht]');
w('\centering');
w('\small');
w(['\caption{Dose-response of extracellular dopamine. Peak: maximum of $\delta eda$ (Eq.~\eqref{eq:dev}). ' ...
   'Peak per dose: peak divided by the dose, as a percentage of its value at $10$ mg (a response proportional to the dose gives $100\%$). ' ...
   '$t_{1/2}$: time during which $\delta eda$ stays above half of its peak.}']);
w('\label{tab:sim:doseresponse}');
w('\begin{tabular}{@{}llrrrrr@{}}');
w('\toprule');
w(' & & \multicolumn{5}{c}{Dose [mg]} \\');
w('\cmidrule(l){3-7}');
w(['$f$ & Quantity & ' strjoin(arrayfun(@(d) sprintf('$%d$',d), dShow, 'UniformOutput', false), ' & ') ' \\']);
for f = fShow
    j = find(abs(fList-f) < 1e-9);
    pk = zeros(1,numel(dShow));  th = pk;
    for k = 1:numel(dShow)
        i = find(DList == dShow(k), 1);
        pk(k) = res(i,j).m.peak*1e3;                 % nM
        th(k) = res(i,j).m.t_half;
    end
    rel = (pk./dShow)/(pk(1)/dShow(1))*100;
    w('\midrule');
    w(sprintf('%g & Peak [nM] & %s \\\\', f, strjoin(arrayfun(@(x) sprintf('%.2f',x), pk,'UniformOutput',false),' & ')));
    w(sprintf(' & Peak per dose [\\%%] & %s \\\\', strjoin(arrayfun(@(x) sprintf('%.0f',x), rel,'UniformOutput',false),' & ')));
    w(sprintf(' & $t_{1/2}$ [h] & %s \\\\', strjoin(arrayfun(@(x) sprintf('%.1f',x), th,'UniformOutput',false),' & ')));
end
w('\bottomrule');
w('\end{tabular}');
w('\end{table}');
fclose(fid);
fprintf('LaTeX table written to %s\n', fullfile(outDir,'tab_doseresponse.tex'));